#Requires -Version 5.1
<#
.SYNOPSIS
    Writes the global commands that address an org member directly (/ryan, /rd, /ryandebraal ...) (MAT-T89).

.DESCRIPTION
    Reads the active members from `orchestrator org members --json`. Every member answers to:
      - their name (lowercased, letters and digits only: "Ryan DeBraal" -> /ryandebraal ... and /ryan for a one-word name),
      - their initials, when the name has two or more words ("Marilyn Monroe" -> /mm),
      - the part of their email before the @ (ryandebraal@mindattic.com -> /ryandebraal).
    An alias only one member answers to gets commands/member/member.md.template filled in for them. An
    alias several members answer to gets commands/member/ambiguous.md.template, which asks "Did you mean
    X or Y?" before doing anything. Each member's filled-in instructions are also kept, outside the
    commands folder, at <GlobalClaudeRoot>\mindattic-members\<email>.md for the ambiguous ones to follow.

    Files this script wrote carry a marker line; one it wrote earlier that no alias needs any more is
    removed. A name that collides with a command this script didn't write (/test, /do ...) is skipped
    and listed.

.PARAMETER WhatIf
    Report what would change; change nothing.
#>
[CmdletBinding()]
param(
    [string]$GlobalClaudeRoot = "$env:USERPROFILE\.claude",
    [string]$MembersJsonPath,   # a members list to use instead of asking the orchestrator (for trying it out)
    [switch]$WhatIf
)

$ErrorActionPreference = 'Stop'
$templates = Join-Path $PSScriptRoot 'commands\member'
$marker = 'generated by MindAttic.Agency/shared/member-commands.ps1'
$commands = Join-Path $GlobalClaudeRoot 'commands'
$instructions = Join-Path $GlobalClaudeRoot 'mindattic-members'
$utf8 = New-Object System.Text.UTF8Encoding $false

function Slug([string]$s) { ($s.ToLowerInvariant() -replace '[^a-z0-9]', '') }

function Write-Generated([string]$path, [string]$body, [string]$what) {
    if ((Test-Path -LiteralPath $path) -and -not ((Get-Content -Raw -LiteralPath $path).Contains($marker))) {
        Write-Host "skipped: $what already exists and isn't a member command"
        return $false
    }
    if ((Test-Path -LiteralPath $path) -and (Get-Content -Raw -LiteralPath $path) -eq $body) { return $true }
    Write-Host "global: $what"
    if (-not $WhatIf) {
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
        [IO.File]::WriteAllText($path, $body, $utf8)
    }
    return $true
}

function Fill([string]$text, $m, [string]$slug) {
    $text.Replace('{{NAME}}', $m.Name).Replace('{{EMAIL}}', $m.Email).Replace('{{SLUG}}', $slug)
}

if ($MembersJsonPath) {
    $json = Get-Content -Raw -LiteralPath $MembersJsonPath
} else {
    $json = orchestrator org members --json
    if ($LASTEXITCODE -ne 0) { throw "orchestrator org members --json failed (exit $LASTEXITCODE)." }
}
$members = @(($json | Out-String) | ConvertFrom-Json) | Where-Object { $_.Status -eq 'active' -and $_.Name -and $_.Email }

$memberText = [IO.File]::ReadAllText((Join-Path $templates 'member.md.template'))
$ambiguousText = [IO.File]::ReadAllText((Join-Path $templates 'ambiguous.md.template'))

# alias -> the members who answer to it
$aliases = [ordered]@{}
foreach ($m in $members) {
    $words = @($m.Name -split '\s+' | Where-Object { Slug $_ })
    $own = @((Slug $m.Name), (Slug ($m.Email -replace '@.*$', '')))
    if ($words.Count -ge 2) { $own += (($words | ForEach-Object { (Slug $_).Substring(0, 1) }) -join '') }
    foreach ($a in ($own | Where-Object { $_ } | Select-Object -Unique)) {
        if (-not $aliases.Contains($a)) { $aliases[$a] = New-Object System.Collections.Generic.List[object] }
        $aliases[$a].Add($m)
    }
}

$keepCommands = @{}
$keepInstructions = @{}
foreach ($m in $members) {
    $file = Join-Path $instructions "$($m.Email).md"
    $keepInstructions[$file] = $true
    [void](Write-Generated $file (Fill $memberText $m (Slug $m.Name)) "instructions for $($m.Name) ($($m.Email))")
}

foreach ($a in $aliases.Keys) {
    $who = @($aliases[$a])
    $dest = Join-Path $commands "$a.md"
    if ($who.Count -eq 1) {
        $body = Fill $memberText $who[0] $a
        $what = "command /$a -> $($who[0].Name) ($($who[0].Email))"
    } else {
        $names = @($who | ForEach-Object { "$($_.Name) ($($_.Email))" })
        $question = (@($names[0..($names.Count - 2)]) -join ', ') + ' or ' + $names[-1]
        $targets = (@($who | ForEach-Object { "``~/.claude/mindattic-members/$($_.Email).md`` for $($_.Name)" }) -join '; ')
        $body = $ambiguousText.Replace('{{SLUG}}', $a).Replace('{{CHOICES}}', ($names -join ', ')).Replace('{{QUESTION}}', $question).Replace('{{TARGETS}}', $targets)
        $what = "command /$a -> asks: Did you mean ${question}?"
    }
    if (Write-Generated $dest $body $what) { $keepCommands[$dest] = $true }
}

foreach ($dir in @($commands, $instructions)) {
    foreach ($f in Get-ChildItem -LiteralPath $dir -Filter '*.md' -File -ErrorAction SilentlyContinue) {
        if ($keepCommands.ContainsKey($f.FullName) -or $keepInstructions.ContainsKey($f.FullName)) { continue }
        if (-not (Get-Content -Raw -LiteralPath $f.FullName).Contains($marker)) { continue }
        Write-Output "removed: $($f.FullName) (no member answers to it any more)"
        if (-not $WhatIf) { Remove-Item -LiteralPath $f.FullName }
    }
}
if ($WhatIf) { Write-Output 'WhatIf: nothing was changed.' }
